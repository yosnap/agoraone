// Turns every hex colour written in the app's CSS into a token (var(--c-<hex>)) and writes
// src/theme-tokens.css with the light value (the original) and a dark one derived from it: light
// surfaces become night blue, dark text becomes light, green accents lean to cyan, amber and reds stay.
// Idempotent: run it again after adding colours (`node scripts/theme-tokens.mjs`).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const roots = ['src'];
const output = 'src/theme-tokens.css';
const files = [];
const walk = dir => { for (const entry of readdirSync(dir, { withFileTypes: true })) {
  const path = join(dir, entry.name);
  if (entry.isDirectory()) walk(path); else if (path.endsWith('.css') && path !== output) files.push(path);
} };
roots.forEach(walk);

const used = new Set();
// Only colours inside a declaration value (after ':' in a block), never a selector like #root.
function tokenise(css) {
  // Custom properties (--name: #hex) are hand-made theme pairs and stay as written.
  let out = '', depth = 0, inValue = false, start = 0;
  for (let index = 0; index < css.length; index++) {
    const char = css[index];
    if (char === '{' || char === '}' || char === ';') { depth += char === '{' ? 1 : char === '}' ? -1 : 0; inValue = false; start = index + 1; }
    else if (char === ':' && depth > 0 && !inValue) inValue = !css.slice(start, index).trim().startsWith('--');
    if (char === '#' && inValue && depth > 0) {
      const match = /^#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{4}|[0-9a-fA-F]{3})(?![0-9a-zA-Z_-])/.exec(css.slice(index));
      if (match) { const hex = normal(match[1]); used.add(hex); out += `var(--c-${hex})`; index += match[0].length - 1; continue; }
    }
    out += char;
  }
  return out;
}
const normal = hex => (hex.length <= 4 ? [...hex].map(c => c + c).join('') : hex).toLowerCase();

for (const file of files) {
  const css = readFileSync(file, 'utf8');
  const done = tokenise(css);
  for (const [, hex] of done.matchAll(/var\(--c-([0-9a-f]{6,8})\)/g)) used.add(hex);
  if (done !== css) writeFileSync(file, done);
}

function hsl(r, g, b) {
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min, s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [h * 60, s, l];
}
function rgb(h, s, l) {
  const k = n => (n + h / 30) % 12, a = s * Math.min(l, 1 - l);
  const f = n => l - a * Math.max(-1, Math.min(k(n) - 3, 9 - k(n), 1));
  return [f(0), f(8), f(4)].map(v => Math.round(v * 255).toString(16).padStart(2, '0')).join('');
}
function dark(hex) {
  const [r, g, b] = [0, 2, 4].map(i => parseInt(hex.slice(i, i + 2), 16) / 255);
  const alpha = hex.slice(6);
  let [h, s, l] = hsl(r, g, b);
  if (l >= 0.6) { // surfaces and light text → night blue
    if (s < 0.35 || l >= 0.9) { h = 214; s = 0.4; } else s *= 0.6; // near-white creams too
    l = 0.06 + (1 - l) * 0.55;
  } else { // dark text, borders and accents → light
    l = Math.min(0.93, 1 - l * 0.75);
    if (h >= 90 && h <= 195 && s > 0.12) { h = 186; s = Math.max(s, 0.5); } else if (s < 0.15) s *= 0.5;
  }
  return rgb(h, s, l) + alpha;
}

const sorted = [...used].sort();
const block = map => sorted.map(hex => `  --c-${hex}: #${map(hex)};`).join('\n');
writeFileSync(output, `/* Generated by scripts/theme-tokens.mjs: one token per colour used in the CSS. Do not edit by hand. */
:root, [data-theme="light"] {
${block(hex => hex)}
}
:root[data-theme="dark"] {
${block(dark)}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${block(dark).replace(/^/gm, '  ')}
  }
}
`);
console.log(`${files.length} hojas, ${sorted.length} colores`);
