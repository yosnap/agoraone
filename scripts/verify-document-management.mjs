import { chromium } from '@playwright/test';
import { appUrl } from './verify-targets.mjs';
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';

const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; let inference = 0;
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', r => { if (r.method() === 'POST' && r.url().endsWith('/messages')) inference++; });
  await page.goto(appUrl(4317));
  // Initial scene load only: headless Chromium renders WebGL in software (~2 fps), so allow it time.
  await page.getByRole('button', { name: 'Luma', exact: true }).click({ timeout: 120_000 });
  await page.getByRole('button', { name: 'Documentos', exact: true }).click();
  await page.getByLabel('Archivo para importar').setInputFiles({ name: 'gestion-prueba.md', mimeType: 'text/markdown', buffer: Buffer.from('# Copia de prueba\nEste texto debe conservarse al renombrar.') });
  await page.getByRole('button', { name: 'Renombrar', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Consultar este documento con Luma' }).click();
  await page.getByRole('button', { name: 'Documentos', exact: true }).click();
  await page.getByRole('button', { name: 'Renombrar', exact: true }).click();
  await page.getByLabel('Nuevo nombre').fill('Cambio cancelado');
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
  await page.getByRole('heading', { name: 'gestion-prueba.md', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Renombrar', exact: true }).click();
  await page.getByLabel('Nuevo nombre').fill('Mis notas verificadas');
  await page.getByRole('button', { name: 'Guardar nombre' }).click();
  await page.getByRole('heading', { name: 'Mis notas verificadas' }).waitFor();
  assert.match(await page.locator('.document-preview pre').innerText(), /Este texto debe conservarse/);
  await page.getByRole('button', { name: 'Conversación', exact: true }).click();
  assert.match(await page.locator('.document-attached').innerText(), /Mis notas verificadas/);
  await page.reload();
  await page.getByRole('button', { name: 'Luma', exact: true }).click();
  await page.getByRole('button', { name: 'Documentos', exact: true }).click();
  await page.getByRole('button', { name: /Mis notas verificadas/ }).click();
  await page.getByRole('button', { name: 'Consultar este documento con Luma' }).click();
  await page.getByRole('button', { name: 'Documentos', exact: true }).click();
  await page.getByRole('button', { name: 'Eliminar copia', exact: true }).click();
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
  await page.getByRole('heading', { name: 'Mis notas verificadas' }).waitFor();
  await page.getByRole('button', { name: 'Eliminar copia', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Confirmar eliminación', exact: true }).scrollIntoViewIfNeeded();
  mkdirSync('.agora', { recursive: true });
  await page.screenshot({ path: '.agora/document-delete-mobile.png' });
  await page.getByRole('button', { name: 'Confirmar eliminación', exact: true }).click();
  await page.getByText('Copia eliminada de la biblioteca.', { exact: false }).waitFor();
  assert.equal(await page.getByRole('button', { name: /Mis notas verificadas/ }).count(), 0);
  await page.getByRole('button', { name: 'Conversación', exact: true }).click();
  assert.equal(await page.locator('.document-attached').count(), 0);
  await page.getByRole('button', { name: 'Documentos', exact: true }).click();
  await page.getByRole('button', { name: 'Bienvenida a la biblioteca', exact: false }).click();
  await page.getByRole('heading', { name: 'Bienvenida a la biblioteca' }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Eliminar copia', exact: true }).count(), 0);
  assert.equal(inference, 0); assert.deepEqual(errors, []);
  console.log('Renombrar, cancelar, persistir, eliminar, retirar adjunto, ejemplos protegidos y móvil: OK. Sin inferencia.');
} finally { await browser.close(); }
